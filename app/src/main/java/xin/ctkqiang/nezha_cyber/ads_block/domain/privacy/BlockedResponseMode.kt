package xin.ctkqiang.nezha_cyber.ads_block.domain.privacy

/**
 * 命中规则时回给客户端的本地应答方式。
 *
 * 三种都是**在本机合成**、都不向上游发起查询，因此都不会把用户的访问意图泄露给解析服务。
 * 它们的区别在于客户端如何理解这次失败：
 *
 * - [NxDomain] 域名不存在（RCODE 3）。语义最标准，缺点是客户端可能据此认为「这个域名没了」
 *   而去尝试备用域名；
 * - [Refused] 本解析器拒绝为你解析（RCODE 5）。它的语义是「我不做这件事」而不是「域名不存在」，
 *   因此不会被误读成域名失效；
 * - [ZeroAddress] 返回 A 记录 `0.0.0.0`。这是 hosts 文件屏蔽域名时通用的写法：地址不是可用的
 *   远端地址，连接会立刻失败，广告内容拿不到。
 *
 * 不同应用对这三种失败的反应并不一致（重试、换域名、或失败后放弃），而哪一种最合适取决于
 * 用户遇到的具体情况，因此做成可选项而不是替用户钉死一种。响应方式只影响被拦截的域名，
 * 放行的域名一律原样转发。
 */
enum class BlockedResponseMode {
    NxDomain,
    Refused,
    ZeroAddress,
}
