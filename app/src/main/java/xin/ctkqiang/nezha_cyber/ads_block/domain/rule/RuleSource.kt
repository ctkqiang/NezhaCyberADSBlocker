package xin.ctkqiang.nezha_cyber.ads_block.domain.rule

/**
 * 规则来源。
 *
 * 来源决定优先级（工程规则第 10 节）：用户显式放行 > 用户显式阻断 > 内置清单 >
 * 应用专属清单 > 关键词规则。界面也必须能区分来源，否则「为什么这条被拦」永远说不清。
 */
enum class RuleSource {
    /** 用户在界面里添加的规则。 */
    USER,

    /** 随应用分发的全局内置清单（assets/domains.txt，第 39 节）。 */
    BUILTIN,

    /**
     * 随应用分发的「按应用生效」广告清单（assets/app_ads.txt，第 44 节）。
     *
     * 与 [BUILTIN] 同属可信内置规则，区别只在作用域：内置清单对所有应用生效，
     * 这一档只对清单里写明的那几个应用生效，因此它需要包名上下文，包名未知时不命中。
     */
    APP_ADS,

    /**
     * 关键词启发式拦截。
     *
     * 单独成一档而不是并进内置清单，有两个原因：
     * 1. 它靠命名特征推断，证据强度低于精编清单，第 17 节要求分类必须显式且可解释——
     *    混在一起会让用户以为 7 万条清单里的每一条都同样可靠；
     * 2. 它可能误伤，因此必须能被单独关掉。
     */
    KEYWORD,
}
