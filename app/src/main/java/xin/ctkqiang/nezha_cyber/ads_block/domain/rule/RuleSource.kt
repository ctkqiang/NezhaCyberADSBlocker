package xin.ctkqiang.nezha_cyber.ads_block.domain.rule

/**
 * 规则来源。
 *
 * 来源决定优先级（工程规则第 10 节）：用户显式放行 > 用户显式阻断 > 内置清单 > 关键词规则。
 * 界面也必须能区分来源，否则「为什么这条被拦」永远说不清。
 */
enum class RuleSource {
    /** 用户在界面里添加的规则。 */
    USER,

    /** 随应用分发的内置清单（assets/domains.txt，第 39 节）。 */
    BUILTIN,

    /**
     * 关键词启发式拦截。
     *
     * 单独成一档而不是并进内置清单，有两个原因：
     * 1. 它靠命名特征推断，证据强度低于精编清单，第 17 节要求分类必须显式且可解释——
     *    混在一起会让用户以为 7 万条清单里的每一条都同样可靠；
     * 2. 它可能误伤，因此必须能被单独关掉。
     */
    KEYWORD,
}
